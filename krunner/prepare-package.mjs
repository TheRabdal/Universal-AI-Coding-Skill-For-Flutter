#!/usr/bin/env node

import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const resourcesDir = path.join(scriptDir, 'resources');
const resourcesMarker = path.join(scriptDir, '.krunner-resources-generated');
const packageJsonPath = path.join(scriptDir, 'package.json');
const markerContent = 'Generated by krunner/prepare-package.mjs';

async function cleanPackage() {
  let marker;
  try {
    marker = await fs.readFile(resourcesMarker, 'utf-8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  if (marker === markerContent) {
    await fs.rm(resourcesDir, { recursive: true, force: true });
    await fs.rm(resourcesMarker, { force: true });
    return;
  }

  try {
    await fs.access(resourcesDir);
  } catch (error) {
    if (error.code === 'ENOENT' && marker === undefined) return;
    throw error;
  }
  throw new Error('Refusing to overwrite krunner/resources without its generated marker.');
}

async function preparePackage() {
  const version = (await fs.readFile(path.join(repoRoot, 'VERSION'), 'utf-8'))
    .trim()
    .replace(/^v/i, '');
  if (!version) throw new Error('VERSION kosong.');

  const packageJson = JSON.parse(await fs.readFile(packageJsonPath, 'utf-8'));
  packageJson.version = version;
  await fs.writeFile(packageJsonPath, `${JSON.stringify(packageJson, null, 2)}\n`);

  await cleanPackage();
  await fs.writeFile(resourcesMarker, markerContent);
  await fs.mkdir(resourcesDir, { recursive: true });
  await fs.copyFile(path.join(repoRoot, 'VERSION'), path.join(resourcesDir, 'VERSION'));
  await fs.copyFile(path.join(repoRoot, 'SKILL.md'), path.join(resourcesDir, 'SKILL.md'));
  const draftDir = path.join(resourcesDir, 'draft');
  await fs.mkdir(draftDir, { recursive: true });
  await fs.copyFile(
    path.join(repoRoot, '.draft', 'rules coding by TheRabdal.md'),
    path.join(draftDir, 'rules coding by TheRabdal.md'),
  );
  await fs.cp(path.join(repoRoot, 'references'), path.join(resourcesDir, 'references'), { recursive: true });

  const additionalSkillsDir = path.join(repoRoot, 'additional-skills');
  try {
    await fs.access(additionalSkillsDir);
    await fs.cp(additionalSkillsDir, path.join(resourcesDir, 'additional-skills'), { recursive: true });
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

if (process.argv.includes('--clean')) {
  await cleanPackage();
} else {
  await preparePackage();
}

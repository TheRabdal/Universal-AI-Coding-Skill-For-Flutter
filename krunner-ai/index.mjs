#!/usr/bin/env node

/**
 * krunner-ai — Universal AI Coding Skill For Flutter
 *
 * Menghasilkan satu file `.krunner` di root project.
 * File ini berisi SEMUA aturan coding, anti-slop, dan security-audit
 * yang digabung menjadi satu — bisa dibaca oleh AI apa pun.
 *
 * Usage:  npx krunner-ai
 *
 * Zero dependency. Node >= 20.12.0.
 */

import { promises as fs, readFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// ── Paths ───────────────────────────────────────────────────────
const __filename = fileURLToPath(import.meta.url);
const __dirname  = path.dirname(__filename);
const REPO_ROOT  = path.resolve(__dirname, '..');

// ── Version (Dipusatkan di file /VERSION) ────────────────────────
function loadVersion() {
  try {
    const raw = readFileSync(path.join(REPO_ROOT, 'VERSION'), 'utf-8');
    return raw.trim().replace(/^v/i, '');
  } catch {
    return '0.1.0';
  }
}

const VERSION = loadVersion();

// ── ANSI helpers ────────────────────────────────────────────────
const fmt = {
  bold:   (t) => `\x1b[1m${t}\x1b[0m`,
  green:  (t) => `\x1b[32m${t}\x1b[0m`,
  cyan:   (t) => `\x1b[36m${t}\x1b[0m`,
  dim:    (t) => `\x1b[2m${t}\x1b[0m`,
  red:   (t) => `\x1b[31m${t}\x1b[0m`,
  yellow: (t) => `\x1b[33m${t}\x1b[0m`,
};

function banner() {
  const verBadge = `v${VERSION}`.padEnd(8, ' ');
  console.log('');
  console.log(fmt.bold(fmt.cyan('  ╔═══════════════════════════════════════════════════╗')));
  console.log(fmt.bold(fmt.cyan(`  ║            🚀  krunner-ai  ${verBadge}               ║`)));
  console.log(fmt.bold(fmt.cyan('  ║     Universal AI Coding Skill For Flutter         ║')));
  console.log(fmt.bold(fmt.cyan('  ╚═══════════════════════════════════════════════════╝')));
  console.log('');
}

function help() {
  banner();
  console.log(`${fmt.bold('Penggunaan:')}

  ${fmt.cyan('npx krunner-ai')}           Generate file .krunner di project saat ini
  ${fmt.cyan('npx krunner-ai --help')}    Tampilkan bantuan ini
  ${fmt.cyan('npx krunner-ai --version')} Tampilkan versi

${fmt.bold('Apa yang terjadi:')}
  CLI membaca semua aturan (SKILL.md, references, anti-slop,
  security-audit) lalu menggabungkannya menjadi SATU
  file ${fmt.bold('.krunner')} di root project Anda.

  File .krunner bisa dibaca oleh AI mana pun — Claude, Gemini,
  Cursor, Codex, Copilot, OpenCode, atau AI lainnya.

${fmt.bold('Contoh:')}
  cd ~/my-flutter-project
  npx krunner-ai
`);
}

// ── Read file safely ────────────────────────────────────────────
async function readSafe(filePath) {
  try {
    return await fs.readFile(filePath, 'utf-8');
  } catch {
    return null;
  }
}

// ── Read all .md files from a directory (recursive, sorted) ─────
async function readAllMd(dirPath) {
  const results = [];
  let entries;
  try {
    entries = await fs.readdir(dirPath, { withFileTypes: true });
  } catch {
    return results;
  }
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const full = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      results.push(...await readAllMd(full));
    } else if (entry.isFile() && entry.name.endsWith('.md')) {
      const content = await readSafe(full);
      if (content) {
        results.push({ name: path.relative(REPO_ROOT, full), content });
      }
    }
  }
  return results;
}

// ── Build .krunner content ──────────────────────────────────────
async function buildKrunner() {
  const sections = [];

  // ── Header ──
  sections.push(`# .krunner — Universal AI Coding Skill For Flutter
# Generated by krunner-ai v${VERSION}
# Tanggal: ${new Date().toISOString()}
#
# FILE INI ADALAH INSTRUKSI UNTUK AI.
# AI yang bekerja pada project ini WAJIB membaca dan mengikuti
# seluruh aturan di bawah. Tidak ada pengecualian.
#
# Aturan ini mencakup:
# 1. Aturan coding universal & Flutter/Dart (SKILL.md)
# 2. References (architecture, coding-standards, flutter-standards, dll.)
# 3. Anti-Slop (kualitas output AI)
# 4. Security Audit (keamanan kode)
`);

  // ── Section 1: SKILL.md (aturan utama) ──
  const skillMd = await readSafe(path.join(REPO_ROOT, 'SKILL.md'));
  if (skillMd) {
    sections.push(`${'='.repeat(80)}
## BAGIAN 1: ATURAN UTAMA (SKILL.md)
${'='.repeat(80)}

${skillMd.trim()}
`);
    console.log(`  ${fmt.green('✓')} SKILL.md`);
  }

  // ── Section 2: References ──
  const refsDir = path.join(REPO_ROOT, 'references');
  const refs = await readAllMd(refsDir);
  if (refs.length) {
    sections.push(`${'='.repeat(80)}
## BAGIAN 2: REFERENCES
${'='.repeat(80)}
`);
    for (const ref of refs) {
      sections.push(`${'─'.repeat(60)}
### ${ref.name}
${'─'.repeat(60)}

${ref.content.trim()}
`);
    }
    console.log(`  ${fmt.green('✓')} references/ (${refs.length} file)`);
  }

  // ── Section 3: Anti-Slop ──
  const antiSlopDir = path.join(REPO_ROOT, 'additional-skills', 'anti-slop');
  // Ambil file aturan utama
  const antiSlopMain = await readSafe(path.join(antiSlopDir, 'antislop.md'));
  const antiSlopGuide = await readSafe(path.join(antiSlopDir, 'GUIDE.md'));
  const antiSlopRules = await readSafe(path.join(antiSlopDir, 'rules', 'antislop.md'));
  const antiSlopSkills = await readAllMd(path.join(antiSlopDir, 'skills'));

  const hasAntiSlop = antiSlopMain || antiSlopGuide || antiSlopRules || antiSlopSkills.length;
  if (hasAntiSlop) {
    sections.push(`${'='.repeat(80)}
## BAGIAN 3: ANTI-SLOP — KUALITAS OUTPUT AI
${'='.repeat(80)}
`);
    if (antiSlopMain) {
      sections.push(`### Anti-Slop — Aturan Utama\n\n${antiSlopMain.trim()}\n`);
    }
    if (antiSlopGuide) {
      sections.push(`### Anti-Slop — Guide\n\n${antiSlopGuide.trim()}\n`);
    }
    if (antiSlopRules) {
      sections.push(`### Anti-Slop — Rules\n\n${antiSlopRules.trim()}\n`);
    }
    for (const skill of antiSlopSkills) {
      sections.push(`${'─'.repeat(60)}
### ${skill.name}
${'─'.repeat(60)}

${skill.content.trim()}
`);
    }
    const count = [antiSlopMain, antiSlopGuide, antiSlopRules].filter(Boolean).length + antiSlopSkills.length;
    console.log(`  ${fmt.green('✓')} anti-slop (${count} file)`);
  }

  // ── Section 4: Security Audit ──
  const secAuditDir = path.join(REPO_ROOT, 'additional-skills', 'security-audit-skill', 'skills', 'security-audit');
  const secFiles = await readAllMd(secAuditDir);
  if (secFiles.length) {
    sections.push(`${'='.repeat(80)}
## BAGIAN 4: SECURITY AUDIT
${'='.repeat(80)}
`);
    for (const sec of secFiles) {
      sections.push(`${'─'.repeat(60)}
### ${sec.name}
${'─'.repeat(60)}

${sec.content.trim()}
`);
    }
    console.log(`  ${fmt.green('✓')} security-audit (${secFiles.length} file)`);
  }

  // ── Footer ──
  sections.push(`${'='.repeat(80)}
## AKHIR INSTRUKSI
##
## AI yang bekerja pada project ini WAJIB mematuhi seluruh aturan di atas.
## Jika ada konflik antar bagian, gunakan urutan prioritas:
##   1. Instruksi eksplisit terbaru dari pengguna
##   2. SKILL.md (Bagian 1)
##   3. References, Anti-Slop, Security Audit (Bagian 2–4)
${'='.repeat(80)}
`);

  return sections.join('\n');
}

// ── Main ────────────────────────────────────────────────────────
async function main() {
  const args = process.argv.slice(2);

  if (args.includes('--help') || args.includes('-h')) { help(); return; }
  if (args.includes('--version') || args.includes('-v')) { console.log(VERSION); return; }

  const projectRoot = process.cwd();

  // Guard: jangan generate di repo sendiri
  if (path.resolve(projectRoot) === path.resolve(REPO_ROOT)) {
    console.log('');
    console.log(fmt.red('  ✗ Anda sedang di dalam repo krunner-ai.'));
    console.log('    Pindah ke folder project Flutter target dulu:');
    console.log(fmt.dim('    cd ~/my-flutter-project'));
    console.log(fmt.dim('    npx krunner-ai'));
    process.exit(1);
  }

  banner();
  console.log(fmt.bold('📦 Generating .krunner'));
  console.log(`   Project: ${fmt.cyan(projectRoot)}`);
  console.log('');

  const content = await buildKrunner();
  const outPath = path.join(projectRoot, '.krunner');
  await fs.writeFile(outPath, content, 'utf-8');

  const sizeKb = (Buffer.byteLength(content, 'utf-8') / 1024).toFixed(1);

  console.log('');
  console.log(fmt.green(fmt.bold(`  ✅ .krunner berhasil dibuat! (${sizeKb} KB)`)));
  console.log(`     ${fmt.dim(outPath)}`);
  console.log('');
  console.log(fmt.dim('  AI mana pun yang bekerja di project ini akan'));
  console.log(fmt.dim('  membaca .krunner dan mengikuti semua aturan.'));
  console.log('');
}

main().catch((err) => {
  console.error(fmt.red('\n  Error:'), err.message || err);
  process.exit(1);
});
